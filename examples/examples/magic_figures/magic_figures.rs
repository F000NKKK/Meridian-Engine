//! Three glowing shapes — a sphere, a cube and a pyramid — orbiting a
//! common center above a textured floor, each spinning on its own axis,
//! each playing its own music track from a *different* container/codec
//! format (`demo-music.mp3`/`.opus`/`.ogg` — real files under
//! `examples/assets/audio/`, identified by signature via
//! `asset-core::AnyAudioDecoder`, never by extension — see ADR 013),
//! and each textured from a different real image file/format
//! (`examples/assets/textures/*.{png,bmp}` — signature-sniffed the same
//! way via `asset-core::AnyImageDecoder`).
//!
//! **Scene composition lives in `assets/scenes/magic_figures.mel`**,
//! compiled by this crate's `build.rs` into a generated module (typed
//! `x:Name` ids, markup checked at build time; ADR 017) and built
//! through `meridian_sdk::dsl` — unlike `physic_figures`, which still
//! reads its file at run time. This scene also needs data the SDK's built-in tags don't carry (glow
//! color, orbit phase/speed, which audio file to play), so this file
//! defines its *own* tags ([`Glow`]/[`Orbit`]/[`AudioTag`]) with the
//! exact same `#[dsl_tag(name = "...")]` macro the SDK's built-ins use
//! — this is the concrete demonstration of the DSL's whole point: a
//! game adds its own vocabulary without touching `meridian-sdk` at all
//! (see [ADR 015](../../docs/adr/015-extensible-scene-dsl.md)).
//!
//! Design notes: docs/notes/meridian-examples.md (`examples/magic_figures`).

mod app;
mod glow;
mod music_rig;
mod orbit;
/// The code generated from `assets/scenes/magic_figures.mel` by this
/// crate's `build.rs` (ADR 017): `Name` has one variant per `x:Name`.
#[expect(
    clippy::allow_attributes,
    reason = "generated by mel-build, which writes #[allow(dead_code)]"
)]
mod scene {
    meridian_sdk::mel_include!("magic_figures");
}
mod shape_spec;
mod sun;

use app::App;
pub(crate) use glow::Glow;
use meridian_sdk::run_windowed_app;
pub(crate) use music_rig::MusicRig;
pub(crate) use orbit::{ORBIT_RADIUS, OrbitTag, orbit_position};
pub(crate) use shape_spec::{ShapeSpec, load_scene, mesh_source_for};
pub(crate) use sun::{SUN_DIRECTION, sun_renderable};

fn main() {
    meridian_examples::app_main::install_diagnostics("magic_figures");
    run_windowed_app("Meridian Engine — Magic Figures", 1024, 768, App::new())
        .expect("windowed app exited with an error");
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn generated_scene_builds_every_named_entity() {
        let names: Vec<_> = load_scene().into_iter().map(|shape| shape.name).collect();
        assert_eq!(names, ["cube", "sphere", "pyramid"]);
    }
}
