//! [`GeneratedResources`]: the Rust source of one resource set.

use super::{ResourceEntry, ResourceSet};
use crate::code_writer::{ALLOW, CodeWriter};

/// `pub struct <Set>;` with one associated constant per entry, the way
/// Visual Studio's `Resources.Designer.cs` has one property.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct GeneratedResources {
    pub code: String,
}

impl GeneratedResources {
    /// Renders `set`, read from `file` (shown in the docs).
    pub fn render(set: &ResourceSet, file: &str) -> Self {
        let mut code = CodeWriter::default();
        code.line("// <auto-generated>");
        code.line(format!("// Generated by meridian-mel-build from {file}."));
        code.line("// Do not edit: it is rewritten on every build.");
        code.line("// </auto-generated>\n");
        code.line(format!("/// The resources of `{file}`."));
        code.line(ALLOW);
        code.line(format!("pub struct {};\n", set.name));
        code.line(ALLOW);
        code.line(format!("impl {} {{", set.name));
        for entry in &set.entries {
            render_entry(&mut code, set, entry);
        }
        code.line("}");
        Self { code: code.text }
    }
}

fn render_entry(code: &mut CodeWriter, set: &ResourceSet, entry: &ResourceEntry) {
    code.line(format!(
        "    /// `{}` of `{}`: `{}`.",
        entry.name,
        set.name,
        entry.value.literal().replace('\n', " ")
    ));
    if let Some(comment) = &entry.comment {
        code.line("    ///");
        for line in comment.lines() {
            code.line(format!("    /// {line}"));
        }
    }
    code.line(format!(
        "    pub const {}: {} = {};",
        entry.constant,
        entry.value.rust_type(),
        entry.value.rust_expr()
    ));
}

#[cfg(test)]
mod tests {
    use std::path::Path;

    use super::*;

    #[test]
    fn every_entry_becomes_a_typed_constant() {
        let text = r##"{ title: { value: "Yog \"Mods\"", comment: "Shown\non top" },
            rows: 20, ratio: 0.5, show: true, accent: { type: "color", value: "#FF8800" } }"##;
        let set = ResourceSet::parse(Path::new("Strings.mres"), "Strings", text).unwrap();
        let code = GeneratedResources::render(&set, "Strings.mres").code;
        for line in [
            "pub struct Strings;",
            "impl Strings {",
            r#"    pub const TITLE: &'static str = "Yog \"Mods\"";"#,
            "    /// Shown",
            "    /// on top",
            "    pub const ROWS: i64 = 20;",
            "    pub const RATIO: f64 = 0.5;",
            "    pub const SHOW: bool = true;",
            "    pub const ACCENT: u32 = 0xFFFF8800;",
        ] {
            assert!(code.contains(line), "missing {line}\n{code}");
        }
        assert_eq!(
            code.matches('{').count(),
            code.matches('}').count(),
            "{code}"
        );
    }
}
