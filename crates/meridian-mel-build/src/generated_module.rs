//! [`GeneratedModule`]: the Rust source of one `<name>.g.rs`.

use crate::MelDocument;
use crate::code_writer::{ALLOW, CodeWriter};
use crate::ui_bindings::UiBindings;

/// Where everything the generated code names lives; applications reach
/// the engine through `meridian-sdk` alone.
const DSL: &str = "::meridian_sdk::dsl";

/// The generated Rust source for one [`MelDocument`].
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct GeneratedModule {
    pub code: String,
}

impl GeneratedModule {
    /// Renders `document`. Its `path` should be absolute: the code embeds
    /// the markup with `include_str!` on that path.
    pub fn render(document: &MelDocument) -> Self {
        let mut code = CodeWriter::default();
        let path = document.path.display().to_string();
        code.line("// <auto-generated>");
        code.line(format!("// Generated by meridian-mel-build from {path}."));
        code.line("// Do not edit: it is rewritten on every build.");
        code.line("// </auto-generated>\n");
        code.line("/// The markup this module was generated from.");
        code.line(ALLOW);
        code.line(format!(
            "pub const SOURCE: &str = include_str!({path:?});\n"
        ));
        render_names(&mut code, document);
        render_alias(&mut code, "Class", document.class.as_deref());
        render_alias(&mut code, "ViewModel", document.view_model.as_deref());
        render_functions(&mut code);
        UiBindings::new(document).render(&mut code);
        Self { code: code.text }
    }
}

fn render_names(code: &mut CodeWriter, document: &MelDocument) {
    let count = document.names.len();
    code.line("/// Every `x:Name` in the document, in document order.");
    code.line(ALLOW);
    code.line("#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash)]");
    code.line("pub enum Name {");
    for named in &document.names {
        code.line(format!(
            "    // @mel {}:{}",
            document.path.display(),
            named.span
        ));
        code.line(format!("    {},", named.variant));
    }
    code.line("}\n");
    code.line(ALLOW);
    code.line("impl Name {");
    code.line("    /// Every variant, in document order.");
    let all: Vec<String> = document
        .names
        .iter()
        .map(|named| format!("Self::{}", named.variant))
        .collect();
    code.line(format!(
        "    pub const ALL: [Self; {count}] = [{}];\n",
        all.join(", ")
    ));
    code.line("    /// The `x:Name` as written in the markup.");
    code.line("    pub fn as_str(self) -> &'static str {");
    code.line("        match self {");
    for named in &document.names {
        code.line(format!(
            "            Self::{} => {:?},",
            named.variant, named.name
        ));
    }
    code.line("        }\n    }\n}\n");
}

fn render_alias(code: &mut CodeWriter, alias: &str, target: Option<&str>) {
    if let Some(target) = target {
        code.line(format!("/// The root's `x:{alias}`."));
        code.line(ALLOW);
        code.line(format!("pub type {alias} = {target};\n"));
    }
}

fn render_functions(code: &mut CodeWriter) {
    code.line("/// Parses [`SOURCE`] and builds it against `registry`.");
    code.line(ALLOW);
    code.line("pub fn build(");
    code.line(format!("    registry: &{DSL}::dsl_core::DslRegistry,"));
    code.line(format!(
        ") -> Result<{DSL}::dsl_core::BuiltNode, {DSL}::DslError> {{"
    ));
    code.line(format!("    {DSL}::build_scene(SOURCE, registry)"));
    code.line("}\n");
    code.line("/// The node named `name` in a tree built by [`build`].");
    code.line(ALLOW);
    code.line("pub fn find(");
    code.line(format!("    root: &{DSL}::dsl_core::BuiltNode,"));
    code.line("    name: Name,");
    code.line(format!(") -> Option<&{DSL}::dsl_core::BuiltNode> {{"));
    code.line("    root.find_named(name.as_str())");
    code.line("}");
}

#[cfg(test)]
mod tests {
    use std::path::Path;

    use super::*;

    fn render(source: &str) -> String {
        let document = MelDocument::parse(Path::new("/scenes/demo.mel"), source).unwrap();
        GeneratedModule::render(&document).code
    }

    #[test]
    fn names_class_and_functions_are_generated() {
        let code = render(r#"<Scene x:Class="crate::Demo"><Entity x:Name="left_arm" /></Scene>"#);
        assert!(
            code.contains(r#"include_str!("/scenes/demo.mel")"#),
            "{code}"
        );
        assert!(
            code.contains("    // @mel /scenes/demo.mel:1:30\n    LeftArm,"),
            "{code}"
        );
        assert!(
            code.contains("pub const ALL: [Self; 1] = [Self::LeftArm];"),
            "{code}"
        );
        assert!(code.contains(r#"Self::LeftArm => "left_arm","#), "{code}");
        assert!(code.contains("pub type Class = crate::Demo;"), "{code}");
        assert!(!code.contains("ViewModel"), "{code}");
        assert!(
            code.contains("::meridian_sdk::dsl::build_scene(SOURCE, registry)"),
            "{code}"
        );
    }

    #[test]
    fn bindings_become_ui_glue() {
        let code = render(
            r#"<StackPanel x:ViewModel="crate::HudVm">
                <TextBlock x:Name="title" text="{x:Bind player?.name, Fallback='-'}" font_size="{x:Bind size, Mode=OneTime}" />
                <TextBlock x:Name="query_box" text="{x:Bind search.text, Mode=TwoWay}" />
                <Border x:Name="mute" width="{x:Bind width(), Mode=TwoWay, BindBack=set_width}" />
            </StackPanel>"#,
        );
        let ui = "::meridian_sdk::ui_core";
        assert!(
            code.contains(&format!("pub title: {ui}::NodeId,")),
            "{code}"
        );
        assert!(
            code.contains(&format!("pub query_box: {ui}::NodeId,")),
            "{code}"
        );
        assert!(
            code.contains("pub fn apply_one_time_bindings(vm: &ViewModel, tree: &mut"),
            "{code}"
        );
        assert!(
            code.contains(&format!(
                "tree.set(names.title, {ui}::properties::text_block::FONT_SIZE, ::core::convert::Into::into(::core::clone::Clone::clone(&(vm.size))))?;"
            )),
            "{code}"
        );
        assert!(
            code.contains(
                "match (|| Some(::core::clone::Clone::clone(&(vm.player.as_ref()?.name))))() {"
            ),
            "{code}"
        );
        assert!(code.contains("None => tree.set(names.title,"), "{code}");
        assert!(
            code.contains("pub fn write_back_bindings(vm: &mut ViewModel"),
            "{code}"
        );
        assert!(
            code.contains("vm.search.text = ::core::convert::Into::into(value);"),
            "{code}"
        );
        assert!(
            code.contains("vm.set_width(::core::convert::Into::into(value));"),
            "{code}"
        );
        assert!(
            code.contains(&format!(
                "change.node == names.mute && change.property == {ui}::properties::element::WIDTH.meta().id"
            )),
            "{code}"
        );
        assert!(code.contains("// @mel /scenes/demo.mel:2:"), "{code}");
        assert_eq!(
            code.matches('{').count(),
            code.matches('}').count(),
            "{code}"
        );
    }

    #[test]
    fn one_way_only_documents_have_no_write_back() {
        let code = render(
            r#"<StackPanel x:ViewModel="V"><TextBlock x:Name="t" text="{x:Bind s}" /></StackPanel>"#,
        );
        assert!(code.contains("pub fn apply_bindings("), "{code}");
        assert!(!code.contains("apply_one_time_bindings"), "{code}");
        assert!(!code.contains("write_back_bindings"), "{code}");
    }

    #[test]
    fn document_without_names_has_an_empty_enum() {
        let code = render("<Scene />");
        assert!(code.contains("pub enum Name {\n}\n\n"), "{code}");
        assert!(
            code.contains("        match self {\n        }\n    }\n}\n"),
            "{code}"
        );
        assert_eq!(
            code.matches('{').count(),
            code.matches('}').count(),
            "{code}"
        );
        assert_eq!(code.matches("#[allow(dead_code").count(), 5, "{code}");
        assert!(!code.contains("Names"), "{code}");
        assert!(code.contains("pub const ALL: [Self; 0] = [];"), "{code}");
    }
}
