//! [`PendingEntity`]: an entity read from a document, not spawned yet.

use meridian_ecs::World;

use super::ComponentsDraft;
use crate::{DisplayName, EntityKey, PrefabPath, SceneEntity};

/// An entity read from a document, not spawned yet.
pub(crate) struct PendingEntity {
    /// Where it is in the document it was read from.
    pub(crate) index: usize,
    pub(crate) key: EntityKey,
    pub(crate) name: Option<DisplayName>,
    pub(crate) prefab: Option<PrefabPath>,
    pub(crate) parent: Option<EntityKey>,
    pub(crate) components: ComponentsDraft,
    /// The instance root a prefab made this entity under.
    pub(crate) generated_by: Option<EntityKey>,
}

impl PendingEntity {
    /// Spawns it into `world`, with its components.
    pub(crate) fn spawn(self, world: &mut World) -> SceneEntity {
        let entity = world.spawn();
        for (_, insert) in self.components.inserts {
            insert(world, entity);
        }
        let mut e = SceneEntity::new(self.key, entity);
        e.name = self.name;
        e.prefab = self.prefab;
        e.parent = self.parent;
        e.kept = self.components.kept;
        e.generated_by = self.generated_by;
        e
    }

    /// This entity (which says `prefab: …`) instanced from `prefab`'s
    /// entities, root first: the entity itself is the instance root, with
    /// the prefab root's name and components under its own (whole
    /// components override), and the rest of the prefab follow it,
    /// generated by it.
    pub(crate) fn instanced(self, mut prefab: Vec<PendingEntity>) -> Vec<PendingEntity> {
        let root = prefab.remove(0);
        let mut group = Vec::with_capacity(prefab.len() + 1);
        for mut child in prefab {
            child.index = self.index;
            child.generated_by.get_or_insert_with(|| self.key.clone());
            group.push(child);
        }
        let merged = PendingEntity {
            name: self.name.or(root.name),
            components: root.components.overridden_by(self.components),
            ..self
        };
        group.insert(0, merged);
        group
    }
}
